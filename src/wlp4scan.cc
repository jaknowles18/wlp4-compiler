std::string tokenKind(std::string state) {
    if (state == "NUM" || state == "NUM0") {
        return "NUM";
    }

    if (state.rfind("ID", 0) == 0) {
        return "ID";
    }

    return state;
}

bool printToken(std::string state, std::string lexeme) {
    std::string kind = tokenKind(state);

    if (kind == "NUM") {
        try {
            std::stoll(lexeme);
        } catch (std::out_of_range&) {
            std::cerr << "ERROR" << std::endl;
            return false;
        }
    }

    std::cout << kind << " " << lexeme << "\n";
    return true;
}

